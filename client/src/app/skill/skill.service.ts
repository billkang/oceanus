@Injectable({ providedIn: 'root' })
export class SkillService {
  list(): Skill[] {
    return MOCK_SKILLS;
  }

  getById(id: string): Skill | undefined {
    return MOCK_SKILLS.find(s => s.id === id);
  }

  getSkillsByIds(ids: string[]): Skill[] {
    return MOCK_SKILLS.filter(s => ids.includes(s.id));
  }
}
